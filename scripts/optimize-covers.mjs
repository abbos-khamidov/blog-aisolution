/**
 * Makes light WebP copies of every cover in public/covers:
 *   public/covers/opt/<name>-640.webp   (cards, ~40–80 KB)
 *   public/covers/opt/<name>-1280.webp  (article hero, ~120–200 KB)
 * and writes lib/cover-variants.generated.ts so components know which exist.
 * The original PNGs stay for link previews (og:image).
 *
 * Run after adding a new cover:  npm run covers:optimize
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const SRC = path.join(process.cwd(), "public", "covers");
const OUT = path.join(SRC, "opt");
const WIDTHS = [640, 1280];

fs.mkdirSync(OUT, { recursive: true });
const names = fs.readdirSync(SRC).filter((f) => /\.(png|jpe?g)$/i.test(f)).sort();
let before = 0;
let after = 0;

for (const file of names) {
  const base = file.replace(/\.[^.]+$/, "");
  const input = path.join(SRC, file);
  before += fs.statSync(input).size;
  for (const width of WIDTHS) {
    const output = path.join(OUT, `${base}-${width}.webp`);
    await sharp(input).resize({ width, withoutEnlargement: true }).webp({ quality: 76, effort: 6 }).toFile(output);
    if (width === 640) after += fs.statSync(output).size;
  }
}

const list = names.map((f) => `  ${JSON.stringify(f.replace(/\.[^.]+$/, ""))}`).join(",\n");
fs.writeFileSync(
  path.join(process.cwd(), "lib", "cover-variants.generated.ts"),
  `// Generated by scripts/optimize-covers.mjs — do not edit by hand.\nexport const OPTIMIZED_COVERS: ReadonlySet<string> = new Set([\n${list}\n]);\n`
);

const mb = (n) => (n / 1024 / 1024).toFixed(1);
console.log(`${names.length} covers: ${mb(before)} MB of PNG → ${mb(after)} MB of 640px WebP`);
